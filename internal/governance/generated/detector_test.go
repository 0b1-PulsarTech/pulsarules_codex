func TestDetector_DirectoryEntryDoesNotPoisonItsFiles(t *testing.T) {
	t.Parallel()

	provider := source.NewFSProvider(fixtureFS(), "", source.SkipSet{})
	detector := NewDetector(provider)
	if detector.isGenerated("db/migrations/") {
		t.Fatal("a directory entry has no content and is not generated")
	}
	if !detector.isGenerated("db/migrations/20260101_init.sql") {
		t.Fatal("sql beside atlas.sum must stay generated after a directory entry was judged")
	}
}

func TestDetector_MemoisesPathsAndAtlasDirs(t *testing.T) {
	t.Parallel()

	counter := &countingProvider{
		Provider: source.NewFSProvider(fixtureFS(), "", source.SkipSet{}),
		reads:    map[string]int{},
	}
	detector := NewDetector(counter)
	for range 3 {
		detector.isGenerated("db/migrations/UP.SQL")
		detector.isGenerated("db/queries/lead.sql")
		detector.isGenerated("hand.go")
	}
	detector.isGenerated("db/migrations/20260101_init.sql")

	want := map[string]int{
		"db/migrations/atlas.sum": 1,
		"db/queries/atlas.sum":    1,
		"db/queries/lead.sql":     1,
		"hand.go":                 1,
	}
	if !reflect.DeepEqual(counter.reads, want) {
		t.Fatalf("reads = %v, want %v", counter.reads, want)
	}
}

func TestDetector_Mark(t *testing.T) {
	t.Parallel()

	provider := source.NewFSProvider(fixtureFS(), "", source.SkipSet{})
	files := []pass.FileChange{
		{Path: "gen.go"},
		{Path: "hand.go"},
		{Path: "missing.go"},
		{Path: "db/migrations/gone.sql"},
		{Path: "db/queries/gone.sql"},
	}
	NewDetector(provider).Mark(files)

	want := []bool{true, false, false, true, false}
	for idx, file := range files {
		if file.Generated != want[idx] {
			t.Errorf("%s Generated = %v, want %v", file.Path, file.Generated, want[idx])
		}
	}
}

func TestDetector_Split(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name           string
		findings       []finding.Finding
		wantKept       []string
		wantSuppressed int
	}{
		{
			name: "findings in generated files are suppressed and counted",
			findings: []finding.Finding{
				{File: "gen.go", Line: 3},
				{File: "db/migrations/UP.SQL"},
				{File: "hand.go", Line: 1},
			},
			wantKept:       []string{"hand.go"},
			wantSuppressed: 2,
		},
		{
			name:           "a finding with no file is never suppressed",
			findings:       []finding.Finding{{AnalyzerID: "commit-lint"}, {File: "gen.go"}},
			wantKept:       []string{""},
			wantSuppressed: 1,
		},
		{name: "no findings", wantKept: nil, wantSuppressed: 0},
		{
			name:           "an unreadable path is kept",
			findings:       []finding.Finding{{File: "missing.go"}},
			wantKept:       []string{"missing.go"},
			wantSuppressed: 0,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			provider := source.NewFSProvider(fixtureFS(), "", source.SkipSet{})
			kept, suppressed := NewDetector(provider).Split(testCase.findings)
			if suppressed != testCase.wantSuppressed {
				t.Fatalf("suppressed = %d, want %d", suppressed, testCase.wantSuppressed)
			}
			var files []string
			for _, finding := range kept {
				files = append(files, finding.File)
			}
			if !reflect.DeepEqual(files, testCase.wantKept) {
				t.Fatalf("kept files = %v, want %v", files, testCase.wantKept)
			}
		})
	}
}

type everythingGenerated struct{ source.Provider }

func (everythingGenerated) Read(string) ([]byte, bool) {
	return []byte("// Code generated by x. DO NOT EDIT.\n"), true
}

func TestDetector_SplitKeepsAFindingWithNoFile(t *testing.T) {
	t.Parallel()

	detector := NewDetector(everythingGenerated{})
	kept, suppressed := detector.Split([]finding.Finding{{AnalyzerID: "commit-lint"}})
	if len(kept) != 1 || suppressed != 0 {
		t.Fatalf(
			"kept %d, suppressed %d; a commit-message finding belongs to no file",
			len(kept),
			suppressed,
		)
	}
}
