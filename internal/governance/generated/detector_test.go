func fixtureFS() fstest.MapFS {
	const goGenerated = "// Code generated by sqlc. DO NOT EDIT.\n\npackage x\n"

	return fstest.MapFS{
		"gen.go":                          {Data: []byte(goGenerated)},
		"hand.go":                         {Data: []byte("package x\n")},
		"db/migrations/atlas.sum":         {Data: []byte("h1:abc=\n")},
		"db/migrations/20260101_init.sql": {Data: []byte("CREATE TABLE a (id int);\n")},
		"db/migrations/UP.SQL":            {Data: []byte("SELECT 1;\n")},
		"db/migrations/README.md":         {Data: []byte("notes\n")},
		"db/migrations/sub/x.sql":         {Data: []byte("SELECT 1;\n")},
		"db/queries/lead.sql":             {Data: []byte("SELECT 1;\n")},
		"top.sql":                         {Data: []byte("SELECT 1;\n")},
		"gen.sql":                         {Data: []byte("-- Code generated by x. DO NOT EDIT.\n")},
	}
}

type countingProvider struct {
	source.Provider
	reads map[string]int
}

func (counter *countingProvider) Read(path string) ([]byte, bool) {
	counter.reads[path]++
	return counter.Provider.Read(path)
}

func TestDetector_IsGenerated(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		path string
		want bool
	}{
		{"go header", "gen.go", true},
		{"hand-written go", "hand.go", false},
		{"missing file", "missing.go", false},
		{"sql beside atlas.sum", "db/migrations/20260101_init.sql", true},
		{"upper-case sql extension", "db/migrations/UP.SQL", true},
		{"sibling dir without atlas.sum", "db/queries/lead.sql", false},
		{"root sql without atlas.sum", "top.sql", false},
		{"dir below atlas.sum", "db/migrations/sub/x.sql", false},
		{"non-sql file in the atlas dir", "db/migrations/README.md", false},
		{"sql with a generated header and no atlas.sum", "gen.sql", true},
		{"atlas dir sql that is not on disk", "db/migrations/gone.sql", true},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			provider := source.NewFSProvider(fixtureFS(), "", source.SkipSet{})
			if got := NewDetector(provider).isGenerated(testCase.path); got != testCase.want {
				t.Fatalf("IsGenerated(%q) = %v, want %v", testCase.path, got, testCase.want)
			}
		})
	}
}

func TestDetector_IsGeneratedAtlasDirDepth(t *testing.T) {
	t.Parallel()

	atlasFS := fstest.MapFS{
		"atlas.sum":              {Data: []byte("h1:abc=\n")},
		"root.sql":               {Data: []byte("SELECT 1;\n")},
		"db/atlas.sum":           {Data: []byte("h1:abc=\n")},
		"db/nested.sql":          {Data: []byte("SELECT 1;\n")},
		"other/unrelated.sql":    {Data: []byte("SELECT 1;\n")},
		"other/deeper/also.sql":  {Data: []byte("SELECT 1;\n")},
		"other/deeper/atlas.sum": {Data: []byte("h1:abc=\n")},
	}
	testCases := []struct {
		name string
		path string
		want bool
	}{
		{"sql beside a root atlas.sum", "root.sql", true},
		{"sql beside a nested atlas.sum", "db/nested.sql", true},
		{"sql in a dir without atlas.sum", "other/unrelated.sql", false},
		{"sql in a deeper atlas dir", "other/deeper/also.sql", true},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			provider := source.NewFSProvider(atlasFS, "", source.SkipSet{})
			if got := NewDetector(provider).isGenerated(testCase.path); got != testCase.want {
				t.Fatalf("IsGenerated(%q) = %v, want %v", testCase.path, got, testCase.want)
			}
		})
	}
}

