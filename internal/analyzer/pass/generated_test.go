package pass

import "testing"

type generatedTestCase struct {
	name string
	src  string
	want bool
}

func TestIsGeneratedSource(t *testing.T) {
	t.Parallel()

	testCases := append(generatedMarkerCases(), generatedNonMarkerCases()...)
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			if got := IsGeneratedSource([]byte(testCase.src)); got != testCase.want {
				t.Fatalf("IsGeneratedSource(%q) = %v, want %v", testCase.src, got, testCase.want)
			}
		})
	}
}

func generatedMarkerCases() []generatedTestCase {
	return []generatedTestCase{
		{
			name: "marker on the first line",
			src:  "// Code generated by sqlc. DO NOT EDIT.\n\npackage dbgen\n",
			want: true,
		},
		{
			name: "marker after a build tag and a blank line",
			src: "//go:build !windows\n\n" +
				"// Code generated by mockgen. DO NOT EDIT.\n\npackage notifier\n",
			want: true,
		},
		{
			name: "mockgen header naming source and destination",
			src: "// Code generated by MockGen. DO NOT EDIT.\n" +
				"// Source: dispatcher.go\n\npackage notifier\n",
			want: true,
		},
		{
			name: "crlf line endings",
			src:  "// Code generated by sqlc. DO NOT EDIT.\r\n\r\npackage dbgen\r\n",
			want: true,
		},
		{
			name: "final line carries the marker without a newline",
			src:  "// Code generated by sqlc. DO NOT EDIT.",
			want: true,
		},
		{
			name: "license block comment before the marker",
			src: "/*\nCopyright 2024.\n*/\n\n" +
				"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n",
			want: true,
		},
		{
			name: "block comment on one line before the marker",
			src: "/* Copyright 2024 */\n\n" +
				"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n",
			want: true,
		},
		{
			name: "dart build_runner header",
			src: "// GENERATED CODE - DO NOT MODIFY BY HAND\n" +
				"// Generator: package:json_serializable\n" +
				"// Target: widget.dart\n\n" +
				"part of 'widget.dart';\n",
			want: true,
		},
		{
			name: "python marker uses the # comment prefix",
			src:  "# Code generated by protoc. DO NOT EDIT.\n\nimport os\n",
			want: true,
		},
		{
			name: "sql marker uses the -- comment prefix",
			src:  "-- Code generated by sqlc. DO NOT EDIT.\n\nSELECT 1;\n",
			want: true,
		},
		{
			name: "csharp auto-generated banner",
			src:  "// <auto-generated>\n// This file was generated.\n// </auto-generated>\n",
			want: true,
		},
		{
			name: "at-generated banner",
			src:  "// @generated by some-tool\n\npackage x\n",
			want: true,
		},
	}
}

func TestIsExemptHeaderLine(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		line string
		want bool
	}{
		{
			name: "generated marker",
			line: "// Code generated by sqlc. DO NOT EDIT.",
			want: true,
		},
		{name: "go build tag", line: "//go:build linux", want: true},
		{name: "legacy build tag", line: "// +build linux", want: true},
		{name: "leading whitespace before the tag", line: "  //go:build linux", want: true},
		{name: "package clause", line: "package foo", want: false},
		{name: "ordinary comment", line: "// a helper", want: false},
		{
			name: "marker without the trailing period is not exempt",
			line: "// Code generated by sqlc. DO NOT EDIT",
			want: false,
		},
		{
			name: "dart analyzer directive",
			line: "// ignore_for_file: implementation_imports",
			want: true,
		},
		{
			name: "indented dart directive",
			line: "  // ignore_for_file: implementation_imports",
			want: true,
		},
		{name: "typescript nocheck", line: "// @ts-nocheck", want: true},
		{name: "typescript expect-error", line: "// @ts-expect-error", want: true},
		{name: "eslint disable", line: "// eslint-disable no-console", want: true},
		{name: "prettier ignore", line: "// prettier-ignore", want: true},
		{name: "svelte ignore", line: "<!-- svelte-ignore a11y-autofocus -->", want: true},
		{name: "shebang", line: "#!/usr/bin/env bash", want: true},
		{name: "go generate directive", line: "//go:generate mockgen -source=x.go", want: true},
		{name: "go embed directive", line: "//go:embed templates/*.tmpl", want: true},
		{name: "nolint directive", line: "//nolint:paralleltest // shared fixture", want: true},
		{
			name: "nolint requires no space before the colon",
			line: "// nolint:paralleltest",
			want: false,
		},
		{name: "python coding cookie", line: "# -*- coding: utf-8 -*-", want: true},
		{
			name: "a licence header is project policy, not an exemption",
			line: "// Copyright 2026 the authors. All rights reserved.",
			want: false,
		},
		{
			name: "prose merely naming a directive is not one",
			line: "// we removed the ignore_for_file directive here",
			want: false,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			if got := IsExemptHeaderLine(testCase.line); got != testCase.want {
				t.Fatalf("IsExemptHeaderLine(%q) = %v, want %v", testCase.line, got, testCase.want)
			}
		})
	}
}

func generatedNonMarkerCases() []generatedTestCase {
	return []generatedTestCase{
		{
			name: "marker below the package clause is not honoured",
			src:  "package dbgen\n\n// Code generated by sqlc. DO NOT EDIT.\n",
			want: false,
		},
		{
			name: "marker without the trailing period",
			src:  "// Code generated by sqlc. DO NOT EDIT\n\npackage dbgen\n",
			want: false,
		},
		{
			name: "prose mentioning generation is not a marker",
			src:  "// This file was generated once. Do not edit.\n\npackage x\n",
			want: false,
		},
		{
			name: "prefix and suffix must not overlap on a short line",
			src:  "// Code generated DO NOT EDIT.\n\npackage x\n",
			want: false,
		},
		{
			name: "hand-written file",
			src:  "// Package doc.\npackage x\n\nfunc F() {}\n",
			want: false,
		},
		{
			name: "empty file",
			src:  "",
			want: false,
		},
		{
			name: "comments only, no marker",
			src:  "// a\n// b\n",
			want: false,
		},
		{
			name: "marker written inside a block comment",
			src:  "/* Code generated by x. DO NOT EDIT. */\n\npackage x\n",
			want: false,
		},
		{
			name: "block comment that never closes",
			src:  "/*\nnever closes\n",
			want: false,
		},
		{
			name: "block comment closes then the package clause is reached",
			src: "/* c */ package x\n\n" +
				"// Code generated by sqlc. DO NOT EDIT.\n",
			want: false,
		},
		{
			name: "marker written inside an html block comment",
			src:  "<!-- Code generated by x. DO NOT EDIT. -->\n\n<html>\n",
			want: false,
		},
		{
			name: "marker written inside a lua block comment",
			src:  "--[[ Code generated by x. DO NOT EDIT. ]]\n\nlocal x = 1\n",
			want: false,
		},
	}
}
