func TestExemptHeaderSpan(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name  string
		lines []string
		want  int
	}{
		{name: "no lines", lines: nil, want: 0},
		{name: "directive line", lines: []string{"//go:build x", "package a"}, want: 1},
		{name: "prose line", lines: []string{"// note", "package a"}, want: 0},
		{
			name:  "single-line pragma docblock",
			lines: []string{"/** @vitest-environment jsdom */", "x"},
			want:  1,
		},
		{
			name:  "multi-line jest docblock",
			lines: []string{"/**", " * @jest-environment jsdom", " */", "x"},
			want:  3,
		},
		{name: "flow pragma", lines: []string{"/* @flow */"}, want: 1},
		{name: "jsx pragma", lines: []string{"/** @jsx h */"}, want: 1},
		{name: "prettier pragma", lines: []string{"/** @prettier */"}, want: 1},
		{name: "prose docblock", lines: []string{"/**", " * Helpers.", " */"}, want: 0},
		{
			name:  "pragma word inside prose is not a pragma",
			lines: []string{"/* see @flow docs */"},
			want:  0,
		},
		{
			name:  "unclosed pragma docblock spans to the end",
			lines: []string{"/**", " * @format"},
			want:  2,
		},
		{name: "unclosed prose docblock", lines: []string{"/*", "text"}, want: 0},
		{
			name:  "jest pragma followed by prose is a hand docblock",
			lines: []string{"/**", " * @jest-environment jsdom", " * Helpers for a.", " */"},
			want:  0,
		},
		{
			name:  "prose followed by a format pragma line is a hand docblock",
			lines: []string{"/**", " * Helpers for a.", " * @format is applied by CI.", " */"},
			want:  0,
		},
		{name: "pure flow strict docblock", lines: []string{"/** @flow strict */", "x"}, want: 1},
		{
			name:  "pure jsdom docblock with args",
			lines: []string{"/**", " * @jest-environment jsdom", " */", "x"},
			want:  3,
		},
		{
			name:  "multi-line svelte ignore spans to the closing arrow",
			lines: []string{"<!-- svelte-ignore a11y-x", "  a11y-y -->", "<!-- hand -->"},
			want:  2,
		},
		{name: "plain html comment", lines: []string{"<!-- hand -->"}, want: 0},
		{
			name:  "multi-line directive block",
			lines: []string{"/* eslint-disable", " a */", "x"},
			want:  2,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			if got := ExemptHeaderSpan(testCase.lines); got != testCase.want {
				t.Fatalf("ExemptHeaderSpan(%q) = %d, want %d", testCase.lines, got, testCase.want)
			}
		})
	}
}

