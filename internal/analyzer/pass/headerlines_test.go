package pass

import (
	"slices"
	"testing"
)

func TestIsExemptHeaderLine(t *testing.T) {
	t.Parallel()

	testCases := slices.Concat(toolingHeaderCases(), []headerTestCase{
		{
			name: "generated marker",
			line: "// Code generated by sqlc. DO NOT EDIT.",
			want: true,
		},
		{name: "go build tag", line: "//go:build linux", want: true},
		{name: "legacy build tag", line: "// +build linux", want: true},
		{name: "leading whitespace before the tag", line: "  //go:build linux", want: true},
		{name: "package clause", line: "package foo", want: false},
		{
			name: "marker without the trailing period is not exempt",
			line: "// Code generated by sqlc. DO NOT EDIT",
			want: false,
		},
		{
			name: "dart analyzer directive",
			line: "// ignore_for_file: implementation_imports",
			want: true,
		},
		{
			name: "indented dart directive",
			line: "  // ignore_for_file: implementation_imports",
			want: true,
		},
		{name: "typescript nocheck", line: "// @ts-nocheck", want: true},
		{name: "typescript expect-error", line: "// @ts-expect-error", want: true},
		{name: "eslint disable", line: "// eslint-disable no-console", want: true},
		{name: "prettier ignore", line: "// prettier-ignore", want: true},
		{name: "svelte ignore", line: "<!-- svelte-ignore a11y-autofocus -->", want: true},
		{name: "shebang", line: "#!/usr/bin/env bash", want: true},
		{name: "go generate directive", line: "//go:generate mockgen -source=x.go", want: true},
		{name: "go embed directive", line: "//go:embed templates/*.tmpl", want: true},
		{name: "nolint directive", line: "//nolint:paralleltest // shared fixture", want: true},
		{
			name: "nolint requires no space before the colon",
			line: "// nolint:paralleltest",
			want: false,
		},
		{name: "python coding cookie", line: "# -*- coding: utf-8 -*-", want: true},
		{
			name: "a licence header is project policy, not an exemption",
			line: "// Copyright 2026 the authors. All rights reserved.",
			want: false,
		},
		{
			name: "prose merely naming a directive is not one",
			line: "// we removed the ignore_for_file directive here",
			want: false,
		},
	})
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			if got := IsExemptHeaderLine(testCase.line); got != testCase.want {
				t.Fatalf("IsExemptHeaderLine(%q) = %v, want %v", testCase.line, got, testCase.want)
			}
		})
	}
}

type headerTestCase struct {
	name string
	line string
	want bool
}

func toolingHeaderCases() []headerTestCase {
	return append(toolingAnnotationCases(), toolingMigrationCases()...)
}

func toolingAnnotationCases() []headerTestCase {
	return []headerTestCase{
		{name: "sqlc one", line: "-- name: Query :one", want: true},
		{name: "sqlc many", line: "-- name: Query :many", want: true},
		{name: "sqlc exec", line: "-- name: Query :exec", want: true},
		{name: "sqlc execrows", line: "-- name: Query :execrows", want: true},
		{name: "sqlc execresult", line: "-- name: Query :execresult", want: true},
		{name: "sqlc execlastid", line: "-- name: Query :execlastid", want: true},
		{name: "sqlc copyfrom", line: "-- name: Query :copyfrom", want: true},
		{name: "sqlc batchexec", line: "-- name: Query :batchexec", want: true},
		{name: "sqlc batchmany", line: "-- name: Query :batchmany", want: true},
		{name: "sqlc batchone", line: "-- name: Query :batchone", want: true},
		{name: "sqlc annotation", line: "-- name: GetUser :one", want: true},
		{name: "sqlc unknown command", line: "-- name: Bad :bogus", want: false},
		{name: "sqlc needs a space after the colon", line: "-- name:GetUser :one", want: false},
		{
			name: "sql prose with IS and a colon is not an annotation",
			line: "-- A survey IS a flow: x",
			want: false,
		},
		{name: "goverter is never a first line", line: "//goverter:converter", want: false},
		{
			name: "pulsarules is never a first line",
			line: "//pulsarules:process-lifetime",
			want: false,
		},
		{name: "lint ignore", line: "//lint:ignore SA1019 reason", want: true},
		{name: "lint file-ignore", line: "//lint:file-ignore SA1019 reason", want: true},
		{name: "lint prefix alone is too broad", line: "//lint:foo bar", want: false},
		{name: "sqlc repeated spaces", line: "-- name:  GetUser   :one", want: false},
		{name: "sqlc missing the command", line: "-- name: GetUser", want: false},
		{name: "sqlc extra field", line: "-- name: GetUser :one extra", want: false},
		{name: "sqlc command without a colon", line: "-- name: GetUser one", want: false},
	}
}

func toolingMigrationCases() []headerTestCase {
	return []headerTestCase{
		{name: "dart language version", line: "// @dart=2.12", want: true},
		{name: "dart language version spaced", line: "// @dart = 2.12", want: true},
		{name: "amd module", line: `/// <amd-module name="x" />`, want: true},
		{name: "amd dependency", line: `/// <amd-dependency path="x" />`, want: true},
		{name: "ts self types", line: `// @ts-self-types="./a.d.ts"`, want: true},
		{name: "v8 ignore file", line: "/* v8 ignore file */", want: true},
		{name: "deno lint ignore file", line: "// deno-lint-ignore-file", want: true},
		{name: "deno fmt ignore file", line: "// deno-fmt-ignore-file", want: true},
		{name: "protolint", line: "// protolint:disable MAX_LINE_LENGTH", want: true},
		{name: "buf lint ignore", line: "// buf:lint:ignore PACKAGE_DEFINED", want: true},
		{name: "triple slash reference", line: `/// <reference types="x" />`, want: true},
		{name: "vitest environment", line: "// @vitest-environment jsdom", want: true},
		{name: "jest ignores line comments", line: "// @jest-environment node", want: false},
		{name: "istanbul ignore file", line: "/* istanbul ignore file */", want: true},
		{name: "c8 ignore", line: "/* c8 ignore start */", want: true},
		{name: "coverage ignore file", line: "// coverage:ignore-file", want: true},
		{name: "ordinary comment", line: "// a helper", want: false},
	}
}
