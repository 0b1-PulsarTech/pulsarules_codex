package filecount

import "testing"

func TestAnalyzeExemptPatterns(t *testing.T) {
	t.Parallel()

	testCases := []fileCountCase{
		{
			name:    "tree pattern exempts the dir itself",
			files:   numbered("internal/gen", 11),
			changed: []string{"internal/gen/f00.go"},
			params:  map[string]any{"exempt": []string{"internal/gen/**"}},
		},
		{
			name:    "tree pattern exempts a nested dir",
			files:   numbered("internal/gen/deep/er", 11),
			changed: []string{"internal/gen/deep/er/f00.go"},
			params:  map[string]any{"exempt": []string{"internal/gen/**"}},
		},
		{
			name:    "tree pattern does not match a sibling prefix",
			files:   numbered("internal/generic", 11),
			changed: []string{"internal/generic/f00.go"},
			params:  map[string]any{"exempt": []string{"internal/gen/**"}},
			want: []string{
				"internal/generic/f00.go:1:package internal/generic has 11 non-test " +
					"source files, max 10",
			},
		},
		{
			name:    "single star does not cross a separator",
			files:   numbered("internal/gen/deep", 11),
			changed: []string{"internal/gen/deep/f00.go"},
			params:  map[string]any{"exempt": []string{"internal/*"}},
			want: []string{
				"internal/gen/deep/f00.go:1:package internal/gen/deep has 11 non-test " +
					"source files, max 10",
			},
		},
		{
			name:    "malformed pattern is reported once",
			files:   numbered("pkg", 3),
			changed: []string{"pkg/f00.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"pkg/f00.go:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
	}
	runFileCountCases(t, testCases)
}

func TestAnalyzeMalformedExempt(t *testing.T) {
	t.Parallel()

	testCases := []fileCountCase{
		{
			name: "malformed pattern anchors on a live source file not a generated one",
			files: merged(numbered("pkg", 3), map[string]string{
				"pkg/gen.go": "// Code generated by tool. DO NOT EDIT.\n\npackage p\n",
			}),
			changed: []string{"pkg/gen.go", "pkg/f00.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"pkg/f00.go:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
		{
			name:    "malformed pattern is reported even when no go file changed",
			files:   map[string]string{"README.md": "x"},
			changed: []string{"README.md"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"README.md:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
		{
			name:    "malformed pattern is reported when the only change is deleted",
			changed: []string{"gone.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"gone.go:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
		{
			name:   "malformed pattern with no changed files reports nothing",
			files:  numbered("pkg", 3),
			params: map[string]any{"exempt": []string{"pkg/["}},
		},
		{
			name:    "tree pattern with a glob base exempts a nested dir",
			files:   numbered("apps/x/internal/gen", 11),
			changed: []string{"apps/x/internal/gen/f00.go"},
			params:  map[string]any{"exempt": []string{"apps/*/internal/**"}},
		},
		{
			name:    "malformed tree pattern is reported",
			files:   numbered("pkg", 3),
			changed: []string{"pkg/f00.go"},
			params:  map[string]any{"exempt": []string{"pk[g/**"}},
			want: []string{
				"pkg/f00.go:1:invalid exempt pattern \"pk[g/**\": syntax error in pattern",
			},
		},
		{
			name:    "malformed pattern does not hide a real finding",
			files:   numbered("pkg", 11),
			changed: []string{"pkg/f00.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"pkg/f00.go:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
				"pkg/f00.go:1:package pkg has 11 non-test source files, max 10",
			},
		},
	}
	runFileCountCases(t, testCases)
}

func TestAnalyzeMalformedExemptSkips(t *testing.T) {
	t.Parallel()

	testCases := []fileCountCase{
		{
			name:    "malformed pattern never anchors on a skipped vendor file",
			files:   merged(numbered("pkg", 3), map[string]string{"vendor/dep/d.go": plainSource}),
			changed: []string{"vendor/dep/d.go", "pkg/f00.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"pkg/f00.go:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
		{
			name:    "malformed pattern skips a vendor file for a live non-go one",
			files:   map[string]string{"vendor/dep/d.go": plainSource, "README.md": "x"},
			changed: []string{"vendor/dep/d.go", "README.md"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want: []string{
				"README.md:1:invalid exempt pattern \"pkg/[\": syntax error in pattern",
			},
		},
		{
			name:    "malformed pattern with only skipped changes has no file to pin",
			files:   map[string]string{"vendor/dep/d.go": plainSource},
			changed: []string{"vendor/dep/d.go"},
			params:  map[string]any{"exempt": []string{"pkg/["}},
			want:    []string{":0:invalid exempt pattern \"pkg/[\": syntax error in pattern"},
		},
	}
	runFileCountCases(t, testCases)
}
