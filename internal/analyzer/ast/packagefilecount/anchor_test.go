package packagefilecount

import "testing"

func TestAnalyzeAnchor(t *testing.T) {
	t.Parallel()

	generated := "// Code generated by tool. DO NOT EDIT.\n\npackage p\n"
	testCases := []fileCountCase{
		{
			name:    "test file skipped for a source anchor",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/a_test.go": plainSource}),
			changed: []string{"pkg/a_test.go", "pkg/f04.go"},
			want:    []string{"pkg/f04.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "generated file skipped for a source anchor",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/gen.go": generated}),
			changed: []string{"pkg/gen.go", "pkg/f02.go"},
			want:    []string{"pkg/f02.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "non go file skipped for a source anchor",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/readme.md": "x"}),
			changed: []string{"pkg/readme.md", "pkg/f01.go"},
			want:    []string{"pkg/f01.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "deleted file skipped for a source anchor",
			files:   numbered("pkg", 11),
			changed: []string{"pkg/removed.go", "pkg/f07.go"},
			want:    []string{"pkg/f07.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "test file is the fallback anchor",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/a_test.go": plainSource}),
			changed: []string{"pkg/a_test.go"},
			want:    []string{"pkg/a_test.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name: "the first changed test file is the fallback anchor",
			files: merged(numbered("pkg", 11), map[string]string{
				"pkg/z_test.go": plainSource, "pkg/a_test.go": plainSource,
			}),
			changed: []string{"pkg/z_test.go", "pkg/a_test.go"},
			want:    []string{"pkg/z_test.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "non go file alone never anchors",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/readme.md": "x"}),
			changed: []string{"pkg/readme.md"},
		},
		{
			name:    "deleted file alone never anchors",
			files:   numbered("pkg", 11),
			changed: []string{"pkg/removed.go"},
		},
		{
			name: "generated test file never anchors even as the fallback",
			files: merged(numbered("pkg", 11), map[string]string{
				"pkg/a_mock_test.go": generated, "pkg/b_test.go": plainSource,
			}),
			changed: []string{"pkg/a_mock_test.go", "pkg/b_test.go"},
			want:    []string{"pkg/b_test.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "generated file alone never anchors",
			files:   merged(numbered("pkg", 11), map[string]string{"pkg/gen.go": generated}),
			changed: []string{"pkg/gen.go"},
		},
	}
	runFileCountCases(t, testCases)
}
