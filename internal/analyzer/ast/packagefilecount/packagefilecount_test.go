const plainSource = "package p\n"

func numbered(dir string, total int) map[string]string {
	files := make(map[string]string, total)
	for index := range total {
		files[fmt.Sprintf("%s/f%02d.go", dir, index)] = plainSource
	}
	return files
}

func merged(sets ...map[string]string) map[string]string {
	out := make(map[string]string)
	for _, set := range sets {
		maps.Copy(out, set)
	}
	return out
}

func buildCtx(
	t *testing.T, files map[string]string, changed []string, params map[string]any,
) *core.AnalysisContext {
	t.Helper()

	mapFS := make(fstest.MapFS, len(files))
	for path, src := range files {
		mapFS[path] = &fstest.MapFile{Data: []byte(src)}
	}
	policy := testpolicy.Defaults()
	changedFiles := make([]core.FileChange, 0, len(changed))
	for _, path := range changed {
		changedFiles = append(
			changedFiles,
			core.FileChange{
				Path: path, Extension: filepath.Ext(path), IsTest: policy.IsTest(path),
			},
		)
	}
	ctx := &core.AnalysisContext{
		Sources:      sources.NewFSProvider(mapFS, "", sources.SkipSet{}),
		ChangedFiles: changedFiles,
		TestPolicy:   policy,
	}
	if params != nil {
		ctx.Config = &core.AnalysisConfig{Analyzers: map[string]core.AnalyzerConfig{
			analyzerID: {Enabled: true, Params: params},
		}}
	}
	return ctx
}

type fileCountCase struct {
	name    string
	files   map[string]string
	changed []string
	params  map[string]any
	want    []string
}

func fileCountCases() []fileCountCase {
	generated := "// Code generated by tool. DO NOT EDIT.\n\npackage p\n"
	return []fileCountCase{
		{
			name:    "eleven files flagged at line one of the changed file",
			files:   numbered("pkg", 11),
			changed: []string{"pkg/f03.go"},
			want:    []string{"pkg/f03.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "ten files ok",
			files:   numbered("pkg", 10),
			changed: []string{"pkg/f00.go"},
		},
		{
			name: "tests not counted",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/a_test.go": plainSource, "pkg/b_test.go": plainSource,
			}),
			changed: []string{"pkg/f00.go"},
		},
		{
			name: "generated not counted",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/gen.go": generated,
			}),
			changed: []string{"pkg/f00.go"},
		},
		{
			name: "non go files not counted",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/readme.md": "x", "pkg/data.sql": "x",
			}),
			changed: []string{"pkg/f00.go"},
		},
	}
}

func entSchemaDir(dir string, total int) map[string]string {
	files := make(map[string]string, total)
	for index := range total {
		files[fmt.Sprintf("%s/f%02d.go", dir, index)] = "package schema\n\n" +
			"import \"entgo.io/ent\"\n\ntype T" + fmt.Sprint(index) + " struct{ ent.Schema }\n"
	}
	return files
}

func entSchemaPlain(total, plain int) map[string]string {
	files := entSchemaDir("schema", total-plain)
	for index := range plain {
		files[fmt.Sprintf("schema/plain%02d.go", index)] = "package schema\n\nconst c = \"x\"\n"
	}
	return files
}

func entSchemaCases() []fileCountCase {
	return []fileCountCase{
		{
			name:    "ent schema dir exempt",
			files:   entSchemaDir("schema", 11),
			changed: []string{"schema/f00.go"},
		},
		{
			name: "ent comment mention with plain files flagged",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/user.go": "package p\n\nimport \"entgo.io/ent\"\n\n// ent.Schema\n",
			}),
			changed: []string{"pkg/f00.go"},
			want:    []string{"pkg/f00.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name: "ent SchemaConfig with plain files flagged",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/user.go": "package p\n\nimport \"entgo.io/ent\"\n\n" +
					"var _ = ent.SchemaConfig{}\n",
			}),
			changed: []string{"pkg/f00.go"},
			want:    []string{"pkg/f00.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name: "ent Schema string literal with plain files flagged",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/user.go": "package p\n\nimport \"entgo.io/ent\"\n\n" +
					"var _ = \"ent.Schema\"\nvar _ ent.Hook\n",
			}),
			changed: []string{"pkg/f00.go"},
			want:    []string{"pkg/f00.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name: "ent schema subpackage import with plain files flagged",
			files: merged(numbered("pkg", 10), map[string]string{
				"pkg/user.go": "package p\n\nimport \"entgo.io/ent/schema/field\"\n\n" +
					"var _ = field.String\n",
			}),
			changed: []string{"pkg/f00.go"},
			want:    []string{"pkg/f00.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "ent schema dir with one plain file among 83 exempt",
			files:   entSchemaPlain(83, 1),
			changed: []string{"schema/f00.go"},
		},
		{
			name:    "ent schema 6 of 11 exempt",
			files:   entSchemaPlain(11, 5),
			changed: []string{"schema/f00.go"},
		},
		{
			name:    "ent schema 5 of 11 flagged",
			files:   entSchemaPlain(11, 6),
			changed: []string{"schema/f00.go"},
			want: []string{
				"schema/f00.go:1:package schema has 11 non-test source files, max 10",
			},
		},
	}
}

