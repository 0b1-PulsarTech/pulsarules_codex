func fileCountParamCases() []fileCountCase {
	return []fileCountCase{
		{
			name: "lookalike import not exempt",
			files: merged(numbered("pkg", 11), map[string]string{
				"pkg/user.go": "package p\n\nimport \"entgo.io/entx\"\n\nvar _ = entx.X\n",
			}),
			changed: []string{"pkg/f00.go"},
			want:    []string{"pkg/f00.go:1:package pkg has 12 non-test source files, max 10"},
		},
		{
			name:    "exempt glob skips dir",
			files:   numbered("internal/gen", 11),
			changed: []string{"internal/gen/f00.go"},
			params:  map[string]any{"exempt": []string{"internal/*"}},
		},
		{
			name:    "exempt glob not matching still flags",
			files:   numbered("internal/gen", 11),
			changed: []string{"internal/gen/f00.go"},
			params:  map[string]any{"exempt": []string{"cmd/*"}},
			want: []string{
				"internal/gen/f00.go:1:package internal/gen has 11 non-test source files, max 10",
			},
		},
		{
			name:    "unchanged dir not reported",
			files:   merged(numbered("big", 11), numbered("small", 2)),
			changed: []string{"small/f00.go"},
		},
		{
			name:    "one finding per dir for several changed files",
			files:   numbered("pkg", 11),
			changed: []string{"pkg/f05.go", "pkg/f01.go"},
			want:    []string{"pkg/f05.go:1:package pkg has 11 non-test source files, max 10"},
		},
		{
			name:    "max_files param",
			files:   numbered("pkg", 3),
			changed: []string{"pkg/f00.go"},
			params:  map[string]any{"max_files": 2},
			want:    []string{"pkg/f00.go:1:package pkg has 3 non-test source files, max 2"},
		},
		{
			name: "extensions param widens count",
			files: merged(numbered("pkg", 6), map[string]string{
				"pkg/a.ts": "x", "pkg/b.ts": "x",
			}),
			changed: []string{"pkg/f00.go"},
			params:  map[string]any{"max_files": 7, "extensions": []string{".go", ".ts"}},
			want:    []string{"pkg/f00.go:1:package pkg has 8 non-test source files, max 7"},
		},
		{
			name:    "root directory",
			files:   map[string]string{"a.go": plainSource, "b.go": plainSource},
			changed: []string{"a.go"},
			params:  map[string]any{"max_files": 1},
			want:    []string{"a.go:1:package . has 2 non-test source files, max 1"},
		},
	}
}

func runFileCountCases(t *testing.T, testCases []fileCountCase) {
	t.Helper()

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			ctx := buildCtx(t, testCase.files, testCase.changed, testCase.params)
			got := make([]string, 0, len(testCase.want))
			for _, finding := range NewAnalyzer().Analyze(ctx) {
				got = append(
					got,
					fmt.Sprintf("%s:%d:%s", finding.File, finding.Line, finding.Message),
				)
			}
			if !slices.Equal(got, testCase.want) {
				t.Fatalf("findings = %q, want %q", got, testCase.want)
			}
		})
	}
}

func TestAnalyze(t *testing.T) {
	t.Parallel()

	runFileCountCases(
		t,
		slices.Concat(
			fileCountCases(), entSchemaCases(), entSchemaTieCases(),
			fileCountScopeCases(), fileCountParamCases(),
		),
	)
}

func TestAnalyzeNilSources(t *testing.T) {
	t.Parallel()

	if got := NewAnalyzer().Analyze(&core.AnalysisContext{}); len(got) != 0 {
		t.Fatalf("findings = %v, want none", got)
	}
}

func TestIdentity(t *testing.T) {
	t.Parallel()

	analyzer := NewAnalyzer()
	if analyzer.ID() != "package-file-count" || analyzer.Stage() != core.StageAST {
		t.Fatalf("id=%q stage=%v", analyzer.ID(), analyzer.Stage())
	}
}
