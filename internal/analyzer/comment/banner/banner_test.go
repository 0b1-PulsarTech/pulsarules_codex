func TestTopOfFile_UnlistedAndFixtures(t *testing.T) {
	t.Parallel()

	testCases := []string{"file.txt", "testdata/bad.go"}
	for _, testCase := range testCases {
		findings := analyzeSource(t, testCase, "// comment\npackage a\n", nil)
		if len(findings) != 0 {
			t.Fatalf("%s: got %d findings, want 0: %+v", testCase, len(findings), findings)
		}
	}
}

func TestTopOfFile_ExtensionOutsideDefaultsSkipped(t *testing.T) {
	t.Parallel()

	const src = "// Copyright 2026\nclass Foo {}\n"
	if findings := analyzeSource(t, "licensed.java", src, nil); len(findings) != 0 {
		t.Fatalf("expected 0 findings for .java by default, got %d: %+v", len(findings), findings)
	}
	config := &pass.AnalysisConfig{Analyzers: map[string]pass.AnalyzerConfig{
		"top-of-file": {
			Enabled: true,
			Params:  map[string]any{"extensions": []string{".go", ".java"}},
		},
	}}
	if findings := analyzeSource(t, "licensed.java", src, config); len(findings) != 1 {
		t.Fatalf(
			"expected 1 finding for .java once opted in, got %d: %+v", len(findings), findings,
		)
	}
}

func TestTopOfFile_GeneratedFlagSkipsTheFile(t *testing.T) {
	t.Parallel()

	const src = "// hand comment\npackage a\n"
	testCases := []struct {
		name      string
		generated bool
		want      int
	}{
		{"flagged generated by the pipeline", true, 0},
		{"not flagged", false, 1},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			change := pass.FileChange{Path: "a.go", Extension: ".go", Generated: testCase.generated}
			findings := analyzeChange(t, change, src, nil)
			if len(findings) != testCase.want {
				t.Fatalf("got %d findings, want %d: %+v", len(findings), testCase.want, findings)
			}
		})
	}
}

type languageCase struct {
	name     string
	file     string
	src      string
	want     int
	line     int
	severity finding.Severity
}

func analyzeSource(t *testing.T, file, src string, config *pass.AnalysisConfig) []finding.Finding {
	t.Helper()

	return analyzeChange(t, pass.FileChange{
		Path:      file,
		Extension: filepath.Ext(file),
		Generated: lexer.IsGeneratedSource([]byte(src)),
	}, src, config)
}

func analyzeChange(
	t *testing.T, change pass.FileChange, src string, config *pass.AnalysisConfig,
) []finding.Finding {
	t.Helper()

	file := change.Path

	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, file)), 0o750); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, file), []byte(src), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	langs := pass.NewLanguageRegistry()
	language.RegisterAll(langs)
	return NewAnalyzer(langs).Analyze(&pass.Context{
		ProjectDir:   dir,
		Sources:      source.NewProvider(dir, source.NewSkipSet(source.DefaultSkipDirs())),
		Config:       config,
		ChangedFiles: []pass.FileChange{change},
	})
}

func runLanguageCases(t *testing.T, testCases []languageCase) {
	t.Helper()

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			findings := analyzeSource(t, testCase.file, testCase.src, nil)
			if len(findings) != testCase.want {
				t.Fatalf("got %d findings, want %d: %+v", len(findings), testCase.want, findings)
			}
			if testCase.want == 0 {
				return
			}
			if findings[0].Line != testCase.line {
				t.Errorf("line = %d, want %d", findings[0].Line, testCase.line)
			}
			if findings[0].Severity != testCase.severity {
				t.Errorf("severity = %d, want %d", findings[0].Severity, testCase.severity)
			}
		})
	}
}

func TestTopOfFile_SeverityParam(t *testing.T) {
	t.Parallel()

	config := &pass.AnalysisConfig{Analyzers: map[string]pass.AnalyzerConfig{
		"top-of-file": {Enabled: true, Params: map[string]any{pass.ParamSeverity: "error"}},
	}}
	findings := analyzeSource(t, "a.ts", "// a note\nconst a = 1\n", config)
	if len(findings) != 1 || findings[0].Severity != finding.SeverityError {
		t.Fatalf("want one error-severity finding, got %+v", findings)
	}
}
