package blocksize

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/0b1-PulsarTech/pulsarules_codex/internal/analyzer/pass"
	"github.com/0b1-PulsarTech/pulsarules_codex/internal/language"
)

type directiveCase struct {
	name string
	file string
	lang string
	src  string
	want int
}

func directiveCases() []directiveCase {
	prose := "// one\n// two\n// three\n// four\n"
	return []directiveCase{
		{
			name: "sqlc annotation then prose",
			file: "a.sql",
			lang: "sql",
			src:  "-- name: X :one\n-- one\n-- two\n-- three\n-- four\nSELECT 1;\n",
			want: 1,
		},
		{
			name: "vitest pragma then prose",
			file: "a.ts",
			lang: "clike",
			src:  "// @vitest-environment jsdom\n" + prose + "const a = 1\n",
			want: 1,
		},
		{
			name: "lint ignore then prose",
			file: "a.go",
			lang: "go",
			src:  "//lint:ignore SA1019 r\n" + prose + "package a\n",
			want: 1,
		},
		{
			name: "pure directive block",
			file: "a.go",
			lang: "go",
			src: "//go:build x\n// +build x\n//nolint:a\n//go:generate b\n//go:embed c\n" +
				"package a\n",
			want: 0,
		},
		{
			name: "directive plus three prose lines",
			file: "a.go",
			lang: "go",
			src:  "//go:build x\n// one\n// two\n// three\npackage a\n",
			want: 0,
		},
		{
			name: "generated marker exempts the block",
			file: "a.go",
			lang: "go",
			src:  "// Code generated by x. DO NOT EDIT.\n" + prose + "package a\n",
			want: 0,
		},
		{
			name: "simplification marker exempts the block",
			file: "a.go",
			lang: "go",
			src:  "package a\n\n// simplification: x\n" + prose + "func f() {}\n",
			want: 0,
		},
	}
}

func TestBigComment_DirectiveLinesDoNotCountTowardABlock(t *testing.T) {
	t.Parallel()

	testCases := directiveCases()
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			if err := os.WriteFile(
				filepath.Join(dir, testCase.file),
				[]byte(testCase.src),
				0o644,
			); err != nil {
				t.Fatalf("write fixture: %v", err)
			}
			langs := pass.NewLanguageRegistry()
			langs.Register(language.Lookup(testCase.lang))
			findings := NewAnalyzer(langs).Analyze(&pass.Context{
				ProjectDir: dir,
				Sources:    pass.NewSourceProvider(dir, pass.NewSkipSet(pass.DefaultSkipDirs())),
				ChangedFiles: []pass.FileChange{
					{Path: testCase.file, Extension: filepath.Ext(testCase.file)},
				},
			})
			if len(findings) != testCase.want {
				t.Fatalf("got %d findings, want %d: %+v", len(findings), testCase.want, findings)
			}
		})
	}
}
