func TestIsDirectiveHeaderLine_Grammar(t *testing.T) {
	t.Parallel()

	testCases := []headerTestCase{
		{name: "global identifier list", line: "/*global window*/", want: true},
		{name: "global with writable flag", line: "/* global a:writable, b */", want: true},
		{name: "globals spelling", line: "/* globals foo, bar */", want: true},
		{name: "global prose", line: "/* global counters live here. */", want: false},
		{name: "global whitespace separated", line: "/* global a b */", want: true},
		{name: "global trailing comma on a multi-line list", line: "/* global a,", want: true},
		{name: "globals dollar identifier", line: "/*globals $*/", want: true},
		{name: "global dangling colon item", line: "/* global :writable */", want: false},
		{name: "global empty list", line: "/* global */", want: false},
		{name: "eslint without a space", line: "/*eslint-disable*/", want: true},
		{name: "nolint bare", line: "//nolint", want: true},
		{name: "nolint linters", line: "//nolint:gosec,errcheck", want: true},
		{name: "nolint with reason", line: "//nolint:gosec // why", want: true},
		{name: "nolint bare with reason", line: "//nolint // why", want: true},
		{name: "nolint prose", line: "//nolint is never used here", want: false},
		{name: "nolint empty linter list", line: "//nolint:", want: false},
		{name: "nolint comma separated with space", line: "//nolint:errcheck, gosec", want: true},
		{name: "nolint space before comma", line: "//nolint:a ,b", want: true},
		{name: "nolint space after colon", line: "//nolint: errcheck", want: true},
		{name: "nolint two spaces before reason", line: "//nolint:errcheck  // why", want: true},
		{name: "nolint tab before reason", line: "//nolint:errcheck\t// why", want: true},
		{name: "nolint hyphenated linter", line: "//nolint:go-critic", want: true},
		{name: "nolint trailing comma", line: "//nolint:errcheck,", want: false},
		{name: "nolint linters then prose", line: "//nolint:gosec is fine", want: false},
		{name: "dart format width", line: "// dart format width=100", want: true},
		{name: "dart format off", line: "// dart format off", want: true},
		{name: "dart format on", line: "// dart format on", want: true},
		{name: "dart format prose", line: "// dart format is enforced by CI", want: false},
		{name: "dart format bad width", line: "// dart format width=wide", want: false},
		{name: "atlas directive", line: "-- atlas:txmode none", want: true},
		{name: "atlas prose", line: "-- atlas: we tried it", want: false},
		{name: "atlas bare", line: "-- atlas:", want: false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			if got := isDirectiveHeaderLine(testCase.line); got != testCase.want {
				t.Fatalf(
					"isDirectiveHeaderLine(%q) = %v, want %v",
					testCase.line,
					got,
					testCase.want,
				)
			}
		})
	}
}

func TestIsDirectiveLine(t *testing.T) {
	t.Parallel()

	testCases := slices.Concat(goDirectiveCases(), tsDirectiveCases())
	for _, testCase := range testCases {
		t.Run(string(testCase.dialect)+" "+testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := IsDirectiveLine(testCase.dialect, testCase.line); got != testCase.want {
				t.Fatalf(
					"IsDirectiveLine(%s, %q) = %v, want %v",
					testCase.dialect, testCase.line, got, testCase.want,
				)
			}
		})
	}
}

type dialectCase struct {
	name    string
	dialect Dialect
	line    string
	want    bool
}

func goDirectiveCases() []dialectCase {
	rows := []headerTestCase{
		{name: "go build tag", line: "//go:build linux", want: true},
		{name: "go noinline", line: "//go:noinline", want: true},
		{name: "spaced go word is prose", line: "// go:noinline", want: false},
		{name: "plus build", line: "// +build linux", want: true},
		{name: "nolint", line: "//nolint:gosec", want: true},
		{name: "nolint is never used here", line: "//nolint is never used here", want: true},
		{name: "lint prefix", line: "//lint:ignore SA1000 why", want: true},
		{name: "lint prefix alone", line: "//lint:x", want: true},
		{name: "goverter", line: "//goverter:converter", want: true},
		{name: "spaced goverter", line: "// goverter:converter", want: true},
		{name: "pulsarules marker", line: "//pulsarules:process-lifetime", want: true},
		{name: "pulsarules marker with a space", line: "// pulsarules: note", want: true},
		{name: "line directive", line: "//line x.go:3", want: true},
		{name: "extern directive", line: "//extern foo", want: true},
		{name: "export directive", line: "//export Foo", want: true},
		{name: "export without a name is prose", line: "//export", want: false},
		{name: "spaced export is prose", line: "// export Foo", want: false},
		{name: "todo shaped prose", line: "//todo:remove this hack", want: false},
		{name: "tool shaped word is prose", line: "//foo:bar", want: false},
		{name: "header directive", line: "// @ts-nocheck", want: true},
		{name: "generated marker", line: "// Code generated by x. DO NOT EDIT.", want: true},
		{name: "ignore is prose", line: "// ignore: unused", want: false},
		{
			name: "ignore for file is a header directive",
			line: "// ignore_for_file: foo",
			want: true,
		},
		{name: "eslint body is prose", line: "// eslint-foo", want: false},
		{name: "ts body is prose", line: "/** @ts-expect-error */", want: false},
		{name: "istanbul body is prose", line: "/* istanbul ignore next */", want: false},
		{name: "noinspection is prose", line: "// noinspection GoUnused", want: false},
		{name: "plain prose", line: "// runs the thing", want: false},
		{name: "mentions a directive midway", line: "// see //go:build for more", want: false},
		{name: "blank comment", line: "//", want: false},
		{name: "empty", line: "", want: false},
	}
	return dialectRows(DialectGo, rows)
}

func tsDirectiveCases() []dialectCase {
	rows := []headerTestCase{
		{name: "eslint", line: "// eslint-disable-next-line", want: true},
		{name: "ts", line: "/** @ts-expect-error */", want: true},
		{name: "pulsarules", line: "// pulsarules:x", want: true},
		{name: "ignore", line: "// ignore: unused", want: true},
		{name: "ignore for file", line: "// ignore_for_file: foo", want: true},
		{name: "prettier", line: " * prettier-ignore", want: true},
		{name: "istanbul", line: "/* istanbul ignore next */", want: true},
		{name: "c8", line: "/* c8 ignore next */", want: true},
		{name: "svelte", line: "// svelte-ignore a11y", want: true},
		{name: "biome", line: "// biome-ignore lint: why", want: true},
		{name: "noinspection", line: "// noinspection JSUnused", want: true},
		{name: "go directive is prose", line: "//go:noinline", want: false},
		{name: "nolint is prose", line: "//nolint:gosec", want: false},
		{
			name: "generated banner is prose",
			line: "// Code generated by x. DO NOT EDIT.",
			want: false,
		},
		{name: "mentions a directive midway", line: "// see eslint-disable for more", want: false},
		{name: "empty", line: "", want: false},
	}
	return dialectRows(DialectTS, rows)
}

func dialectRows(dialect Dialect, rows []headerTestCase) []dialectCase {
	cases := make([]dialectCase, 0, len(rows))
	for _, row := range rows {
		cases = append(cases, dialectCase{
			name: row.name, dialect: dialect, line: row.line, want: row.want,
		})
	}
	return cases
}

func TestPulsarulesMarker(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name      string
		body      string
		wantToken string
		wantOK    bool
	}{
		{"bare marker", "pulsarules:process-lifetime", "process-lifetime", true},
		{"marker with a reason", " pulsarules:x reason", "x reason", true},
		{"space after the colon", "pulsarules: x", "", false},
		{"tab after the colon", "pulsarules:\tx", "", false},
		{"no token", "pulsarules:", "", false},
		{"not a marker", "note pulsarules:x", "", false},
		{"empty", "", "", false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			token, ok := PulsarulesMarker(testCase.body)
			if token != testCase.wantToken || ok != testCase.wantOK {
				t.Fatalf(
					"PulsarulesMarker(%q) = (%q, %v), want (%q, %v)",
					testCase.body, token, ok, testCase.wantToken, testCase.wantOK,
				)
			}
		})
	}
}
