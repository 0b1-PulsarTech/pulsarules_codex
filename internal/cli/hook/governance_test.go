func TestGovernChanges_SuppressionBlock(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	initGitRepo(t, dir)
	emDash := "\u2014"
	writeHookFile(
		t, dir, "gen.go",
		"// Code generated by sqlc. DO NOT EDIT.\n\npackage demo\n\n// a "+emDash+" b\n",
	)
	writeHookFile(t, dir, "hand.go", "package demo\n\n// c "+emDash+" d\n")

	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}

	block, count := governor{loader: testLoader()}.changes(dir, status, testEmojiCatalog(t))
	if count != 1 {
		t.Fatalf("count = %d, want 1 (the generated file's finding is suppressed)", count)
	}
	if !strings.Contains(block, "  1 suppressed in generated files\n") {
		t.Fatalf("block does not state the suppression:\n%s", block)
	}
}

func runDirtyCheck(t *testing.T, configYAML string) (string, int) {
	t.Helper()

	dir := t.TempDir()
	initGitRepo(t, dir)
	writeHookFile(t, dir, "hand.go", "package demo\n\n// c \u2014 d\n")
	if configYAML != "" {
		writeHookFile(t, dir, ".pulsarules.yaml", configYAML)
	}
	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}
	return governor{loader: testLoader()}.changes(dir, status, testEmojiCatalog(t))
}

type projectConfigCase struct {
	name       string
	configYAML string
	wantCount  int
	wantConfig string
	wantHand   bool
}

func projectConfigCases() []projectConfigCase {
	return []projectConfigCase{
		{"no file is unchanged", "", 1, "", true},
		{
			"valid file is applied",
			"version: 1\nanalyzers: {typographic-markers: {enabled: false}}\n",
			0, "", false,
		},
		{
			"unknown key is one error and others still run",
			"version: 1\nbogus: 1\n",
			2, "line 2: bogus: unknown key", true,
		},
		{
			"second document is one error",
			"version: 1\n---\nversion: 1\n",
			2, "only one YAML document is allowed", true,
		},
		{
			"widening override is one error",
			"version: 1\nanalyzers: {file-size: {enabled: false}}\n" +
				"overrides: [{files: [a], analyzers: {file-size: {enabled: true}}}]\n",
			2, "an override can only narrow it", true,
		},
	}
}

func TestGovernChanges_ProjectConfig(t *testing.T) {
	t.Parallel()

	for _, testCase := range projectConfigCases() {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			block, count := runDirtyCheck(t, testCase.configYAML)
			if count != testCase.wantCount {
				t.Fatalf("count = %d, want %d:\n%s", count, testCase.wantCount, block)
			}
			wantErrors := 0
			if testCase.wantConfig != "" {
				wantErrors = 1
			}
			if got := strings.Count(block, "[error] config:"); got != wantErrors {
				t.Errorf("config errors = %d, want %d:\n%s", got, wantErrors, block)
			}
			if !strings.Contains(block, testCase.wantConfig) {
				t.Errorf("block lacks %q:\n%s", testCase.wantConfig, block)
			}
			if strings.Contains(block, "hand.go") != testCase.wantHand {
				t.Errorf("hand.go finding wanted = %v:\n%s", testCase.wantHand, block)
			}
		})
	}
}

func TestGovernanceBlock(t *testing.T) {
	t.Parallel()

	warning := finding.Finding{
		AnalyzerID: "file-size", Severity: finding.SeverityWarning, Message: "too long",
		File: "a.go", Line: 3,
	}
	testCases := []struct {
		name      string
		report    findings.Report
		wantBlock string
		wantCount int
	}{
		{name: "nothing found is no block", report: findings.Report{}},
		{name: "suppression alone is no block", report: findings.Report{Suppressed: 4}},
		{
			name:      "findings under the header",
			report:    findings.Report{Findings: []finding.Finding{warning}},
			wantBlock: "\nGovernance checks:\n  [warning] file-size: too long (a.go:3)\n",
			wantCount: 1,
		},
		{
			name:   "the suppression follows the findings in the report's own words",
			report: findings.Report{Findings: []finding.Finding{warning}, Suppressed: 2},
			wantBlock: "\nGovernance checks:\n  [warning] file-size: too long (a.go:3)\n" +
				"  2 suppressed in generated files\n",
			wantCount: 1,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			block, count := governanceBlock(testCase.report)
			if block != testCase.wantBlock || count != testCase.wantCount {
				t.Fatalf("governanceBlock() = %q, %d, want %q, %d",
					block, count, testCase.wantBlock, testCase.wantCount)
			}
		})
	}
}

func TestGovernanceBlock_SuppressionPhrase(t *testing.T) {
	t.Parallel()

	report := findings.Report{
		Findings: []finding.Finding{
			{AnalyzerID: "x", Severity: finding.SeverityInfo, Message: "m"},
		},
		Suppressed: 7,
	}
	block, _ := governanceBlock(report)

	const phrase = "7 suppressed in generated files"
	if !strings.HasSuffix(block, "  "+phrase+"\n") {
		t.Fatalf("hook %q must end with the phrase %q", block, phrase)
	}
}

//nolint:paralleltest // captureStderr swaps os.Stderr.
func TestGovernanceCheck_CatalogFailureYieldsNothing(t *testing.T) {
	check := governor{loader: testLoader()}.check(func() (*emoji.Catalog, error) {
		return nil, errors.New("catalog unavailable")
	})
	var (
		block string
		count int
	)
	stderr := captureStderr(t, func() { block, count = check(t.TempDir(), vcs.Status{}) })

	if block != "" || count != 0 {
		t.Errorf("check() = %q, %d, want no block and no findings", block, count)
	}
	if !strings.Contains(stderr, "hook: get emoji catalog: catalog unavailable") {
		t.Errorf("stderr = %q, want the catalog failure", stderr)
	}
}

func testLoader() func() *loader.Loader {
	return func() *loader.Loader { return loader.NewLoader(registry.ConfigRules()) }
}

func TestGovernor_Changes_UsesItsLoader(t *testing.T) {
	t.Parallel()

	const unlistedAnalyzer = "version: 1\nanalyzers: {not-an-analyzer: {enabled: false}}\n"
	testCases := []struct {
		name        string
		loader      func() *loader.Loader
		wantFinding bool
	}{
		{"registry rules reject it", testLoader(), true},
		{"a loader built for any analyzer accepts it", func() *loader.Loader {
			return loader.NewLoader(projectfile.Rules{AnyAnalyzer: true})
		}, false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			initGitRepo(t, dir)
			writeHookFile(t, dir, ".pulsarules.yaml", unlistedAnalyzer)
			block, _ := governor{loader: testCase.loader}.changes(
				dir, vcs.Status{}, testEmojiCatalog(t),
			)
			if got := strings.Contains(block, "unknown analyzer"); got != testCase.wantFinding {
				t.Fatalf("block = %q, unknown-analyzer finding = %v, want %v",
					block, got, testCase.wantFinding)
			}
		})
	}
}
