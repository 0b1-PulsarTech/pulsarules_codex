func TestPrintHookError_StaysOnOneLine(t *testing.T) {
	t.Parallel()

	var out strings.Builder
	printHookError(&out, "get templates", errors.New("open a\n[ERROR] forged"))
	want := `hook: get templates: open a\n[ERROR] forged` + "\n"
	if out.String() != want {
		t.Errorf("output = %q, want %q", out.String(), want)
	}
}

func TestGovernChanges_EmptyRepo(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if out, err := exec.CommandContext(t.Context(), "git", "-C", dir, "init").
		CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}

	got, count := governChanges(dir, status, nil, testEmojiCatalog(t))
	if got != "" {
		t.Errorf("block = %q, want empty for an empty repo", got)
	}
	if count != 0 {
		t.Errorf("count = %d, want 0 for an empty repo", count)
	}
}

