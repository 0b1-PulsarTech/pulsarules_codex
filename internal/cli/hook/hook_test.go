func TestGovernChanges_SuppressionBlock(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	initGitRepo(t, dir)
	emDash := "\u2014"
	writeHookFile(
		t, dir, "gen.go",
		"// Code generated by sqlc. DO NOT EDIT.\n\npackage demo\n\n// a "+emDash+" b\n",
	)
	writeHookFile(t, dir, "hand.go", "package demo\n\n// c "+emDash+" d\n")

	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}

	block, count := governChanges(dir, status, nil, testEmojiCatalog(t))
	if count != 1 {
		t.Fatalf("count = %d, want 1 (the generated file's finding is suppressed)", count)
	}
	if !strings.Contains(block, "1 finding(s) suppressed in generated files") {
		t.Fatalf("block does not state the suppression:\n%s", block)
	}
}

func initGitRepo(t *testing.T, dir string) {
	t.Helper()

	if out, err := exec.CommandContext(t.Context(), "git", "-C", dir, "init").
		CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
}

func writeHookFile(t *testing.T, dir, name, content string) {
	t.Helper()

	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), disk.File); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}

func runDirtyCheck(t *testing.T, configYAML string) (string, int) {
	t.Helper()

	dir := t.TempDir()
	initGitRepo(t, dir)
	writeHookFile(t, dir, "hand.go", "package demo\n\n// c \u2014 d\n")
	if configYAML != "" {
		writeHookFile(t, dir, ".pulsarules.yaml", configYAML)
	}
	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}
	return governChanges(dir, status, nil, testEmojiCatalog(t))
}

type projectConfigCase struct {
	name       string
	configYAML string
	wantCount  int
	wantConfig string
	wantHand   bool
}

func projectConfigCases() []projectConfigCase {
	return []projectConfigCase{
		{"no file is unchanged", "", 1, "", true},
		{
			"valid file is applied",
			"version: 1\nanalyzers: {typographic-markers: {enabled: false}}\n",
			0, "", false,
		},
		{
			"unknown key is one error and others still run",
			"version: 1\nbogus: 1\n",
			2, "line 2: bogus: unknown key", true,
		},
		{
			"second document is one error",
			"version: 1\n---\nversion: 1\n",
			2, "only one YAML document is allowed", true,
		},
		{
			"widening override is one error",
			"version: 1\nanalyzers: {file-size: {enabled: false}}\n" +
				"overrides: [{files: [a], analyzers: {file-size: {enabled: true}}}]\n",
			2, "an override can only narrow it", true,
		},
	}
}

func TestGovernChanges_ProjectConfig(t *testing.T) {
	t.Parallel()

	for _, testCase := range projectConfigCases() {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			block, count := runDirtyCheck(t, testCase.configYAML)
			if count != testCase.wantCount {
				t.Fatalf("count = %d, want %d:\n%s", count, testCase.wantCount, block)
			}
			wantErrors := 0
			if testCase.wantConfig != "" {
				wantErrors = 1
			}
			if got := strings.Count(block, "[error] config:"); got != wantErrors {
				t.Errorf("config errors = %d, want %d:\n%s", got, wantErrors, block)
			}
			if !strings.Contains(block, testCase.wantConfig) {
				t.Errorf("block lacks %q:\n%s", testCase.wantConfig, block)
			}
			if strings.Contains(block, "hand.go") != testCase.wantHand {
				t.Errorf("hand.go finding wanted = %v:\n%s", testCase.wantHand, block)
			}
		})
	}
}

func TestHookStop_RealGovernance(t *testing.T) {
	t.Setenv("TMPDIR", t.TempDir())

	index, assets, err := knowledge.Load("")
	if err != nil {
		t.Fatalf("load knowledge: %v", err)
	}
	dir := t.TempDir()
	initGitRepo(t, dir)
	writeHookFile(t, dir, "violation.go", "package x\n\n// bad note \u2014 here\n")
	var out bytes.Buffer
	t.Setenv("PULSARULES_PROJECT_DIR", dir)
	t.Setenv("PULSARULES_SKILLS_DIR", "")
	disp := newHookDispatcher(index, testEmojiCatalog(t), templates.New(assets), nil, &out)

	_ = disp.Dispatch("stop", []byte(`{"session_id":"real-governance"}`))
	for _, want := range []string{
		"Governance checks:", "typographic-markers", "go vet", "violation.go",
	} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("stop output missing %q:\n%s", want, out.String())
		}
	}
}

