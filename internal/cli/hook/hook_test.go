//nolint:paralleltest // t.Setenv and the os.Stdin/os.Stdout swaps bar t.Parallel.
func TestCommand_Run_PassesTheCallersEnvironmentToTheDispatcher(t *testing.T) {
	t.Setenv("TMPDIR", t.TempDir())

	project, skills := t.TempDir(), t.TempDir()
	writeHookFile(t, project, "go.mod", "module x\n")
	if err := os.MkdirAll(
		filepath.Join(skills, "gopls-navigation"),
		disk.DirPrivate,
	); err != nil {
		t.Fatalf("mkdir skill: %v", err)
	}
	writeHookFile(t, skills, "gopls-navigation/SKILL.md", "x")
	payload := `{"session_id":"SID","tool_name":"Grep","tool_input":{"pattern":"a.go"}}`

	testCases := []struct {
		name string
		env  flags.Environment
		want bool
	}{
		{"both given", flags.Environment{ProjectDir: project, SkillsDir: skills}, true},
		{"no skills dir", flags.Environment{ProjectDir: project}, false},
		{"no project dir", flags.Environment{SkillsDir: skills}, false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			inj := remy.NewInjector(remy.Config{DuckTypeElements: true})
			bindHookWithoutCatalog(t, inj, t.TempDir())
			stdin, err := os.CreateTemp(t.TempDir(), "stdin")
			if err != nil {
				t.Fatalf("create stdin: %v", err)
			}
			session := strings.Replace(payload, "SID", testCase.name, 1)
			if _, err = stdin.WriteString(session); err != nil {
				t.Fatalf("write stdin: %v", err)
			}
			if _, err = stdin.Seek(0, 0); err != nil {
				t.Fatalf("rewind stdin: %v", err)
			}
			savedStdin := os.Stdin
			os.Stdin = stdin
			defer func() { os.Stdin = savedStdin }()

			out := captureStream(t, &os.Stdout, func() {
				if err = New(testCase.env).Run(inj, []string{"pre-search"}); err != nil {
					t.Errorf("Run(pre-search) = %v, want nil", err)
				}
			})
			if got := out != ""; got != testCase.want {
				t.Errorf("pre-search emitted = %v, want %v:\n%s", got, testCase.want, out)
			}
		})
	}
}

func TestGovernanceBlock(t *testing.T) {
	t.Parallel()

	warning := finding.Finding{
		AnalyzerID: "file-size", Severity: finding.SeverityWarning, Message: "too long",
		File: "a.go", Line: 3,
	}
	testCases := []struct {
		name      string
		report    findings.Report
		wantBlock string
		wantCount int
	}{
		{name: "nothing found is no block", report: findings.Report{}},
		{name: "suppression alone is no block", report: findings.Report{Suppressed: 4}},
		{
			name:      "findings under the header",
			report:    findings.Report{Findings: []finding.Finding{warning}},
			wantBlock: "\nGovernance checks:\n  [warning] file-size: too long (a.go:3)\n",
			wantCount: 1,
		},
		{
			name:   "the suppression follows the findings in the report's own words",
			report: findings.Report{Findings: []finding.Finding{warning}, Suppressed: 2},
			wantBlock: "\nGovernance checks:\n  [warning] file-size: too long (a.go:3)\n" +
				"  2 suppressed in generated files\n",
			wantCount: 1,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			block, count := governanceBlock(testCase.report)
			if block != testCase.wantBlock || count != testCase.wantCount {
				t.Fatalf("governanceBlock() = %q, %d, want %q, %d",
					block, count, testCase.wantBlock, testCase.wantCount)
			}
		})
	}
}

func TestGovernanceBlock_SuppressionPhrase(t *testing.T) {
	t.Parallel()

	report := findings.Report{
		Findings: []finding.Finding{
			{AnalyzerID: "x", Severity: finding.SeverityInfo, Message: "m"},
		},
		Suppressed: 7,
	}
	block, _ := governanceBlock(report)

	const phrase = "7 suppressed in generated files"
	if !strings.HasSuffix(block, "  "+phrase+"\n") {
		t.Fatalf("hook %q must end with the phrase %q", block, phrase)
	}
}

