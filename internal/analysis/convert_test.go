const markGeneratedContent = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n"

//nolint:ireturn // matches sources.NewProvider's own factory signature
func newTestProvider(dir string) sources.Provider {
	return sources.NewProvider(dir, sources.NewSkipSet(sources.DefaultSkipDirs()))
}

type markGeneratedTestCase struct {
	name     string
	setup    func(t *testing.T, dir string) []core.FileChange
	provider func(dir string) sources.Provider
	wantFlag []bool
}

func TestMarkGenerated(t *testing.T) {
	t.Parallel()

	testCases := markGeneratedTestCases()
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			files := testCase.setup(t, dir)
			markGenerated(files, testCase.provider(dir))
			if len(files) != len(testCase.wantFlag) {
				t.Fatalf("got %d files, want %d", len(files), len(testCase.wantFlag))
			}
			for i, want := range testCase.wantFlag {
				if files[i].Generated != want {
					t.Errorf("files[%d].Generated = %v, want %v", i, files[i].Generated, want)
				}
			}
		})
	}
}

func markGeneratedTestCases() []markGeneratedTestCase {
	return []markGeneratedTestCase{
		{
			name: "mixed generated and non-generated files",
			setup: func(t *testing.T, dir string) []core.FileChange {
				t.Helper()
				const markPlainContent = "package x\n\nfunc F() {}\n"
				writeMarkGeneratedFile(t, dir, "generated.go", markGeneratedContent)
				writeMarkGeneratedFile(t, dir, "plain.go", markPlainContent)
				return []core.FileChange{
					{Path: "generated.go", Extension: ".go"},
					{Path: "plain.go", Extension: ".go"},
				}
			},
			provider: newTestProvider,
			wantFlag: []bool{true, false},
		},
		{
			name: "nil sources leaves flags false",
			setup: func(t *testing.T, dir string) []core.FileChange {
				t.Helper()
				writeMarkGeneratedFile(t, dir, "generated.go", markGeneratedContent)
				return []core.FileChange{{Path: "generated.go", Extension: ".go"}}
			},
			provider: func(string) sources.Provider { return nil },
			wantFlag: []bool{false},
		},
		{
			name: "path that does not exist leaves flag false",
			setup: func(t *testing.T, dir string) []core.FileChange {
				t.Helper()
				return []core.FileChange{{Path: "missing.go", Extension: ".go"}}
			},
			provider: newTestProvider,
			wantFlag: []bool{false},
		},
	}
}

func writeMarkGeneratedFile(t *testing.T, dir, relPath, content string) {
	t.Helper()
	full := filepath.Join(dir, relPath)
	if err := os.WriteFile(full, []byte(content), fsperm.File); err != nil {
		t.Fatalf("write %q: %v", full, err)
	}
}

func TestMarkGenerated_AtlasMigrationDir(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		path string
		want bool
	}{
		{"sql beside atlas.sum is generated", "db/migrations/20260101_init.sql", true},
		{"sibling dir without atlas.sum is not", "db/queries/lead.sql", false},
		{"nested dir below atlas.sum is not", "db/migrations/sub/x.sql", false},
		{"non-sql file in the atlas dir is not", "db/migrations/README.md", false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			files := []core.FileChange{{Path: testCase.path}}
			markGenerated(files, newTestProvider(atlasFixture(t)))
			if files[0].Generated != testCase.want {
				t.Errorf("Generated = %v, want %v", files[0].Generated, testCase.want)
			}
		})
	}
}

type renamesFailingRepo struct{ *goldenRepo }

func (renamesFailingRepo) StagedRenames(int) ([]vcs.Rename, error) {
	return nil, errors.New("rename probe exploded")
}

func TestSession_StagedRenamesLogsProbeFailure(t *testing.T) {
	t.Parallel()

	var logs bytes.Buffer
	sess := NewSession(renamesFailingRepo{&goldenRepo{root: t.TempDir()}}, "", nil, nil)
	sess.logger = slog.New(slog.NewTextHandler(&logs, nil))

	if renames := sess.stagedRenames(); len(renames) != 0 {
		t.Fatalf("stagedRenames() = %v, want none", renames)
	}
	if !strings.Contains(logs.String(), "rename probe exploded") {
		t.Fatalf("log output %q does not report the probe failure", logs.String())
	}
}
