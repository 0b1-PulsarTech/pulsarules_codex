type splitTestCase struct {
	name           string
	files          []core.FileChange
	findings       []core.Finding
	wantKept       []string
	wantSuppressed int
}

func generatedFiles() []core.FileChange {
	return []core.FileChange{
		{Path: "internal/dbgen/lead.sql.go", Extension: ".go", Generated: true},
		{Path: "internal/dbgen/task.sql.go", Extension: ".go", Generated: true},
		{Path: "internal/repo/lead.go", Extension: ".go"},
	}
}

func TestSplitGenerated(t *testing.T) {
	t.Parallel()

	for _, testCase := range splitTestCases() {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			ctx := &core.AnalysisContext{ChangedFiles: testCase.files}
			got := splitGenerated(ctx, testCase.findings)
			if got.SuppressedGenerated != testCase.wantSuppressed {
				t.Fatalf(
					"SuppressedGenerated = %d, want %d",
					got.SuppressedGenerated,
					testCase.wantSuppressed,
				)
			}
			if len(got.Findings) != len(testCase.wantKept) {
				t.Fatalf(
					"kept %d findings, want %d: %+v",
					len(got.Findings),
					len(testCase.wantKept),
					got.Findings,
				)
			}
			for i, want := range testCase.wantKept {
				if got.Findings[i].File != want {
					t.Errorf("kept[%d].File = %q, want %q", i, got.Findings[i].File, want)
				}
			}
		})
	}
}

func splitTestCases() []splitTestCase {
	files := generatedFiles()
	return []splitTestCase{
		{
			name:  "findings in generated files are suppressed and counted",
			files: files,
			findings: []core.Finding{
				{AnalyzerID: "shadowing", File: "internal/dbgen/lead.sql.go", Line: 12},
				{AnalyzerID: "shadowing", File: "internal/dbgen/task.sql.go", Line: 8},
				{AnalyzerID: "naming", File: "internal/repo/lead.go", Line: 4},
			},
			wantKept:       []string{"internal/repo/lead.go"},
			wantSuppressed: 2,
		},
		{
			name:  "a finding with no file is never suppressed",
			files: files,
			findings: []core.Finding{
				{AnalyzerID: "commit-lint", File: ""},
				{AnalyzerID: "file-size", File: "internal/dbgen/lead.sql.go"},
			},
			wantKept:       []string{""},
			wantSuppressed: 1,
		},
		{
			name:  "no generated file means nothing is filtered",
			files: []core.FileChange{{Path: "internal/repo/lead.go", Extension: ".go"}},
			findings: []core.Finding{
				{AnalyzerID: "naming", File: "internal/repo/lead.go"},
			},
			wantKept:       []string{"internal/repo/lead.go"},
			wantSuppressed: 0,
		},
		{
			name:           "no findings at all",
			files:          files,
			findings:       nil,
			wantKept:       nil,
			wantSuppressed: 0,
		},
		{
			name:  "every finding suppressed leaves an empty set with a count",
			files: files,
			findings: []core.Finding{
				{AnalyzerID: "shadowing", File: "internal/dbgen/lead.sql.go"},
				{AnalyzerID: "shadowing", File: "internal/dbgen/task.sql.go"},
			},
			wantKept:       nil,
			wantSuppressed: 2,
		},
	}
}

func TestSplitGenerated_UnlistedFiles(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFileAt(t, dir, "gen.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage x\n")
	writeFileAt(t, dir, "hand.go", "package x\n")

	ctx := &core.AnalysisContext{
		ChangedFiles: nil,
		Sources: sources.NewSourceProvider(
			dir,
			sources.NewSkipSet(sources.DefaultSkipDirs()),
		),
	}
	findings := []core.Finding{
		{AnalyzerID: "golangci-lint", File: "gen.go"},
		{AnalyzerID: "golangci-lint", File: "hand.go"},
		{AnalyzerID: "golangci-lint", File: "missing.go"},
	}

	got := splitGenerated(ctx, findings)
	if got.SuppressedGenerated != 1 {
		t.Fatalf("SuppressedGenerated = %d, want 1", got.SuppressedGenerated)
	}
	if len(got.Findings) != 2 {
		t.Fatalf("kept %d findings, want 2: %+v", len(got.Findings), got.Findings)
	}
}

func TestAnalyzeIncludeGeneratedKeepsEverything(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	gitInitRepo(t, dir)
	emDash := "\u2014"
	writeFileAt(
		t,
		dir,
		"gen.go",
		"// Code generated by sqlc. DO NOT EDIT.\n\npackage x\n\n// a note "+emDash+" here\n",
	)
	runGitAt(t, dir, "add", "gen.go")

	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}

	testCases := []struct {
		name             string
		includeGenerated bool
		wantFindings     bool
		wantSuppressed   bool
	}{
		{
			name:             "suppressed by default",
			includeGenerated: false,
			wantFindings:     false,
			wantSuppressed:   true,
		},
		{
			name:             "reported with include-generated",
			includeGenerated: true,
			wantFindings:     true,
			wantSuppressed:   false,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			cfg := config.Defaults()
			cfg.ApplyPreset()
			cfg.IncludeGenerated = testCase.includeGenerated

			result := NewSession(repo, "", nil, cfg).Analyze(ScopeChanged, nil, FileSetChanged)

			hasEmDash := false
			for _, f := range result.Findings {
				if f.AnalyzerID == "typographic-markers" {
					hasEmDash = true
				}
			}
			if hasEmDash != testCase.wantFindings {
				t.Fatalf(
					"typographic-markers finding present = %v, want %v",
					hasEmDash,
					testCase.wantFindings,
				)
			}
			if (result.SuppressedGenerated > 0) != testCase.wantSuppressed {
				t.Fatalf(
					"SuppressedGenerated = %d, want suppression = %v",
					result.SuppressedGenerated,
					testCase.wantSuppressed,
				)
			}
		})
	}
}

func atlasFixture(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	writeFileAtDir(t, dir, "db/migrations/atlas.sum", "h1:abc=\n")
	writeFileAtDir(t, dir, "db/migrations/20260101_init.sql", "CREATE TABLE a (id int);\n")
	writeFileAtDir(t, dir, "db/migrations/README.md", "notes\n")
	writeFileAtDir(t, dir, "db/queries/lead.sql", "SELECT 1;\n")
	writeFileAtDir(t, dir, "db/migrations/sub/x.sql", "SELECT 1;\n")
	writeFileAtDir(t, dir, "top.sql", "SELECT 1;\n")
	return dir
}

func TestSplitGenerated_AtlasMigrationDir(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name           string
		file           string
		wantSuppressed int
	}{
		{"sql beside atlas.sum is generated", "db/migrations/20260101_init.sql", 1},
		{"upper-case extension is still sql", "db/migrations/UP.SQL", 1},
		{"sibling dir without atlas.sum is hand-written", "db/queries/lead.sql", 0},
		{"root sql without atlas.sum is hand-written", "top.sql", 0},
		{"nested dir below atlas.sum is hand-written", "db/migrations/sub/x.sql", 0},
		{"non-sql file in the atlas dir is hand-written", "db/migrations/README.md", 0},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			ctx := &core.AnalysisContext{Sources: newTestSourceProvider(atlasFixture(t))}
			findings := []core.Finding{{AnalyzerID: "top-of-file", File: testCase.file}}

			got := splitGenerated(ctx, findings)
			if got.SuppressedGenerated != testCase.wantSuppressed {
				t.Fatalf("SuppressedGenerated = %d, want %d",
					got.SuppressedGenerated, testCase.wantSuppressed)
			}
		})
	}
}

func TestIsGeneratedFile_DirectoryEntryNoPoison(t *testing.T) {
	t.Parallel()

	known := map[string]bool{}
	provider := newTestSourceProvider(atlasFixture(t))
	if isGeneratedFile("db/migrations/", known, provider) {
		t.Fatal("a directory entry has no content and is not generated")
	}
	if !isGeneratedFile("db/migrations/20260101_init.sql", known, provider) {
		t.Fatal("sql beside atlas.sum must stay generated after a directory entry was judged")
	}
}
