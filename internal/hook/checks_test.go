func TestRunGovernanceCheck_EmptyRepo(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if out, err := exec.CommandContext(t.Context(), "git", "-C", dir, "init").
		CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}

	got, count := RunGovernanceCheck(repo, status, nil, governance.ScopeChanged)
	if got != "" {
		t.Errorf("block = %q, want empty for an empty repo", got)
	}
	if count != 0 {
		t.Errorf("count = %d, want 0 for an empty repo", count)
	}
}

func TestRunGovernanceCheck_SuppressionBlock(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	gitInit(t, dir)
	emDash := "\u2014"
	writeFile(
		t, dir, "gen.go",
		"// Code generated by sqlc. DO NOT EDIT.\n\npackage x\n\n// a "+emDash+" b\n",
	)
	writeFile(t, dir, "hand.go", "package x\n\n// c "+emDash+" d\n")

	repo, err := vcs.Open(dir)
	if err != nil {
		t.Fatalf("vcs.Open: %v", err)
	}
	status, err := repo.WorktreeStatus()
	if err != nil {
		t.Fatalf("WorktreeStatus: %v", err)
	}

	block, count := RunGovernanceCheck(repo, status, nil, governance.ScopeChanged)
	if count != 1 {
		t.Fatalf("count = %d, want 1 (the generated file's finding is suppressed)", count)
	}
	if !strings.Contains(block, "1 finding(s) suppressed in generated files") {
		t.Fatalf("block does not state the suppression:\n%s", block)
	}
}

func writeFile(t *testing.T, dir, name, content string) {
	t.Helper()

	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), disk.File); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}
